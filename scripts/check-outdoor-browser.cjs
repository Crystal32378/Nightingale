const BASE_URL = process.env.NIGHTINGALE_QA_URL || 'http://127.0.0.1:5178';
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];const audio=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('response',r=>{if(r.url().includes('/audio/outdoor/')) audio.push({url:r.url(),status:r.status()})});
 await page.addInitScript(()=>{
  window.__played=[];window.__stopped=[];
  const start=AudioBufferSourceNode.prototype.start,stop=AudioBufferSourceNode.prototype.stop;
  AudioBufferSourceNode.prototype.start=function(...args){window.__played.push({duration:this.buffer?.duration,time:Date.now()});return start.apply(this,args)};
  AudioBufferSourceNode.prototype.stop=function(...args){window.__stopped.push(Date.now());return stop.apply(this,args)};
 });
 await page.goto(BASE_URL + '/?flow=last300m&photo=1');
 await page.getByRole('button',{name:'開始',exact:true}).click();
 await page.getByRole('button',{name:'我到出口2了',exact:true}).waitFor();
 await page.waitForFunction(()=>window.__played.length>=1);
 await page.getByRole('button',{name:'我到出口2了',exact:true}).click();
 await page.getByPlaceholder('跟我說你看到什麼').fill('大安路一段116巷');
 await page.getByRole('button',{name:'傳送',exact:true}).click();
 await page.getByRole('button',{name:'過完了',exact:true}).waitFor();
 await page.waitForFunction(()=>window.__played.length>=2);
 if(await page.getByRole('button',{name:'我在哪',exact:true}).count()) throw Error('Replay exposed during crossing');
 await page.screenshot({path:'/tmp/nightingale-crossing.png',fullPage:true});
 const during=await page.evaluate(()=>window.__played.length);
 await page.waitForTimeout(5000);
 if(await page.evaluate(()=>window.__played.length)!==during) throw Error('Extra voice during crossing');
 await page.getByRole('button',{name:'過完了',exact:true}).click();
 await page.waitForResponse(r=>r.url().endsWith('/leda/cp2.along.wav'));
 await page.waitForTimeout(250);
 if(!audio.some(a=>a.url.endsWith('/leda/cp2.after.wav')) || !audio.some(a=>a.url.endsWith('/leda/cp2.along.wav'))) throw Error('Missing along sequence');
 await page.screenshot({path:'/tmp/nightingale-after-crossing.png',fullPage:true});
 await page.getByRole('combobox',{name:'聲音'}).selectOption('Puck');
 await page.getByRole('button',{name:'我在哪',exact:true}).click();
 await page.waitForResponse(r=>r.url().endsWith('/puck/cp2.after.wav'));
 await page.waitForTimeout(200);
 await page.getByRole('combobox',{name:'聲音'}).selectOption('quiet');
 const muted=await page.evaluate(()=>window.__played.length);
 await page.waitForTimeout(3800);
 if(await page.evaluate(()=>window.__played.length)!==muted) throw Error('Queued voice leaked after mute');
 if(audio.some(a=>a.url.endsWith('/puck/cp2.along.wav'))) throw Error('Along fetched despite mute');
 await page.getByRole('combobox',{name:'聲音'}).selectOption('Puck');
 await page.getByRole('button',{name:'拍招牌',exact:true}).click();
 await page.waitForResponse(r=>r.url().endsWith('/puck/photo.remind.wav'));
 await page.waitForTimeout(200);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 const result={audio,played:await page.evaluate(()=>window.__played),stopped:await page.evaluate(()=>window.__stopped),errors,overflow};
 fs.writeFileSync('/tmp/nightingale-voice-browser-result.json',JSON.stringify(result,null,2));
 console.log(JSON.stringify(result,null,2));

 await page.goto(BASE_URL + '/?flow=last300m');
 await page.getByRole('button',{name:'開始',exact:true}).click();
 await page.getByRole('button',{name:'我到出口2了'}).click();
 await page.getByPlaceholder('跟我說你看到什麼').waitFor();
 await page.route('**/observations',async route=>{const response=await route.fetch();await new Promise(r=>setTimeout(r,900));await route.fulfill({response})});
 await page.getByPlaceholder('跟我說你看到什麼').fill('大安路一段116巷');
 await page.getByRole('button',{name:'傳送',exact:true}).click();
 await page.getByRole('button',{name:'幫我問',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 const beforeHelp=audio.length;
 await page.waitForTimeout(1500);
 if(audio.length!==beforeHelp) throw Error('Late navigation audio fetched over help');
 console.log('PASS: help dialog suppresses late navigation audio');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
